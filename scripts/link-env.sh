#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SOURCE_ENV="${1:-"$ROOT_DIR/.env.local"}"

if [[ ! -f "$SOURCE_ENV" ]]; then
  echo "Missing $SOURCE_ENV"
  echo "Create it from .env.example first: cp .env.example .env.local"
  exit 1
fi

# Locally prood.com is the gateway (apps/web) on port 3001. Open it, not the apps' own ports, so
# the dashboard, admin, checkout, docs and API share one origin, as they do in production.
GATEWAY="http://localhost:3001"
API_INTERNAL="http://localhost:3005"

# The variables this script owns. They are removed from the copy of the root file and written
# again below, so an old subdomain-era .env.local cannot leave a stale value behind.
OWNED='BETTER_AUTH_URL|NEXT_PUBLIC_AUTH_URL|NEXT_PUBLIC_WEB_URL|NEXT_PUBLIC_DASHBOARD_URL|NEXT_PUBLIC_ADMIN_URL|NEXT_PUBLIC_API_URL|NEXT_PUBLIC_DOCS_URL|API_PUBLIC_URL|CHECKOUT_URL|COMMERCE_API_URL|AUTH_COOKIE_DOMAIN|PASSKEY_RP_ID|PASSKEY_ORIGINS|DASHBOARD_ORIGIN|ADMIN_ORIGIN|DOCS_ORIGIN|CHECKOUT_ORIGIN|API_ORIGIN'

write_app_env() {
  local app="$1"
  local with_better_auth_url="$2"
  local with_passkeys="$3"
  local with_origins="$4"
  local target="$ROOT_DIR/apps/$app/.env.local"

  {
    echo "# Generated by scripts/link-env.sh from $(basename "$SOURCE_ENV")."
    echo "# Do not edit this file directly; update the repo root .env.local instead."
    echo
    awk -v owned="$OWNED" '$0 !~ ("^(" owned ")=")' "$SOURCE_ENV"
    echo
    echo "# One origin: everything the browser sees is the gateway on $GATEWAY."
    echo "NEXT_PUBLIC_WEB_URL=\"$GATEWAY\""
    echo "NEXT_PUBLIC_DASHBOARD_URL=\"$GATEWAY\""
    echo "NEXT_PUBLIC_ADMIN_URL=\"$GATEWAY/admin\""
    echo "NEXT_PUBLIC_API_URL=\"$GATEWAY\""
    echo "NEXT_PUBLIC_DOCS_URL=\"$GATEWAY\""
    echo "API_PUBLIC_URL=\"$GATEWAY\""
    echo "CHECKOUT_URL=\"$GATEWAY/pay\""
    # Server to server: straight to the API app, not through the gateway.
    echo "NEXT_PUBLIC_AUTH_URL=\"$API_INTERNAL\""
    echo "COMMERCE_API_URL=\"$API_INTERNAL/v1\""
    # Storefront auth infers its base URL per store origin: no BETTER_AUTH_URL.
    if [[ "$with_better_auth_url" == "yes" ]]; then
      echo "BETTER_AUTH_URL=\"$GATEWAY\""
    fi
    if [[ "$with_passkeys" == "yes" ]]; then
      echo "PASSKEY_RP_ID=\"localhost\""
      echo "PASSKEY_ORIGINS=\"$GATEWAY\""
    fi
    # The gateway's rewrite targets. They match apps/web's local defaults, written out here
    # so the file shows where each path goes.
    if [[ "$with_origins" == "yes" ]]; then
      echo "DASHBOARD_ORIGIN=\"http://localhost:3002\""
      echo "DOCS_ORIGIN=\"http://localhost:3003\""
      echo "CHECKOUT_ORIGIN=\"http://localhost:3004\""
      echo "API_ORIGIN=\"$API_INTERNAL\""
      echo "ADMIN_ORIGIN=\"http://localhost:3006\""
    fi
  } > "$target"

  echo "Wrote apps/$app/.env.local"
}

#                 app         BETTER_AUTH_URL  passkeys  gateway origins
write_app_env "api"        "yes" "yes" "no"
write_app_env "storefront" "no"  "no"  "no"
write_app_env "dashboard"  "yes" "yes" "no"
write_app_env "checkout"   "yes" "no"  "no"
write_app_env "admin"      "yes" "yes" "no"
write_app_env "web"        "yes" "no"  "yes"
write_app_env "docs"       "yes" "no"  "no"
